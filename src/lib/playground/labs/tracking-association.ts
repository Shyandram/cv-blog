// ---------------------------------------------------------------------------------------------- the synthetic scene
// Three people-shaped blocks, 30 x 40 pixels, in a 160 x 128 frame over 30 frames. Objects 0 (orange) and 1 (blue) walk toward
// each other along one line at 4 pixels per frame, stand at the same x at frame MEET and each turns back; object 2 (green) walks
// along the bottom and never touches them. Object 1 is 8 pixels lower than object 0 and is drawn in front. Everything is
// generated by code (no images), and mirrored in NumPy by scripts/figures/playground_goldens_tracking.py.
export const W = 160, H = 128, T = 30, K = 3;
export const BOX_W = 30, BOX_H = 40, SPEED = 4, MEET = 14;
export const Y = [40, 48, 100];
export const SHIRT_ROWS = 22, PIXEL_NOISE = 0.03, RENDER_SEED = 2024, EMBED_BINS = 4;
const BACKGROUND = [0.86, 0.86, 0.84];
const SHIRTS = [[0.90, 0.55, 0.12], [0.15, 0.40, 0.85], [0.20, 0.65, 0.30]];
const TROUSERS = [[0.45, 0.30, 0.10], [0.10, 0.15, 0.62], [0.15, 0.15, 0.20]];
/** Seed of the detection jitter (a fixed field of standard normals; the slider only scales it, so it never re-rolls). */
export const JITTER_SEED = 16;
export const DEFAULTS = { lambda: 1, sigma: 2.5, frame: 15 };

/** True boxes [f][object]. */
export function truthBoxes(): Box[][] {
  const out: Box[][] = [];
  for (let f = 0; f < T; f++) {
    const xa = f <= MEET ? 30 + SPEED * f : 30 + SPEED * MEET - SPEED * (f - MEET);
    const xb = f <= MEET ? 30 + 2 * SPEED * MEET - SPEED * f : 30 + SPEED * MEET + SPEED * (f - MEET);
    out.push([xa, xb, 20 + SPEED * f].map((cx, k) => ({ cx, cy: Y[k], w: BOX_W, h: BOX_H })));
  }
  return out;
}
/** Render frame f: flat background, the three blocks (later objects in front; shirt on top, trousers below), Gaussian pixel noise. */
export function renderFrame(f: number, truth: Box[][]): Rgb {
  const data = new Float32Array(W * H * 3), base = new Float64Array(W * H * 3);
  for (let i = 0; i < W * H; i++) { base[3 * i] = BACKGROUND[0]; base[3 * i + 1] = BACKGROUND[1]; base[3 * i + 2] = BACKGROUND[2]; }
  for (let k = 0; k < K; k++) {
    const b = truth[f][k], [x0, x1] = pixelRange(b.cx, b.w, W), [y0, y1] = pixelRange(b.cy, b.h, H), top = Math.floor(b.cy - b.h / 2 + 0.5);
    for (let y = y0; y < y1; y++) {
      const c = y - top < SHIRT_ROWS ? SHIRTS[k] : TROUSERS[k];
      for (let x = x0; x < x1; x++) { const i = 3 * (y * W + x); base[i] = c[0]; base[i + 1] = c[1]; base[i + 2] = c[2]; }
    }
  }
  const noise = normalField(W * H * 3, RENDER_SEED + f);
  for (let i = 0; i < base.length; i++) data[i] = Math.min(1, Math.max(0, base[i] + PIXEL_NOISE * noise[i]));
  return { w: W, h: H, data };
}
export interface Scene { truth: Box[][]; frames: Rgb[] }
let sceneCache: Scene | undefined;
export function getScene(): Scene {
  if (!sceneCache) { const truth = truthBoxes(); sceneCache = { truth, frames: Array.from({ length: T }, (_, f) => renderFrame(f, truth)) }; }
  return sceneCache;
}
/** Jittered detection boxes [f][slot]. The detector does not report identities: slot j of frame f holds object (j + f) mod 3. */
export function detectionBoxes(truth: Box[][], sigma: number, seed = JITTER_SEED): { box: Box; truth: number }[][] {
  const noise = normalField(T * K * 4, seed);
  return truth.map((row, f) => Array.from({ length: K }, (_, j) => {
    const k = (j + f) % K, t = row[k], n = (c: number) => noise[(f * K + k) * 4 + c];
    return { truth: k, box: { cx: t.cx + sigma * n(0), cy: t.cy + sigma * n(1), w: t.w + sigma * n(2) / 2, h: t.h + sigma * n(3) / 2 } };
  }));
}
/** Detections with their colour-histogram embeddings (they depend on the jitter but not on lambda). */
export function detectionsFor(scene: Scene, sigma: number, seed = JITTER_SEED): Detection[][] {
  return detectionBoxes(scene.truth, sigma, seed).map((row, f) => row.map(d => ({ ...d, embedding: colourEmbedding(scene.frames[f], d.box, EMBED_BINS) })));
}

export interface LabRun {
  run: TrackerRun;
  detections: Detection[][];
  /** owner[f][track]: the true object the track holds in frame f. */
  owner: number[][];
  switches: number; firstSwitch: number; wrongFrames: number; total: number; meanIou: number; mota: number;
}
export function runLab(scene: Scene, lambda: number, sigma: number, seed = JITTER_SEED, detections?: Detection[][]): LabRun {
  const dets = detections ?? detectionsFor(scene, sigma, seed), run = runTracker(dets, { lambda });
  const owner = run.identity.map(row => { const o = new Array<number>(K).fill(-1); row.forEach((track, obj) => { o[track] = obj; }); return o; });
  const sw = countSwitches(run.identity);
  return { run, detections: dets, owner, switches: sw.switches, firstSwitch: sw.firstFrame, wrongFrames: sw.wrongFrames, total: sw.total, meanIou: meanTrackIou(run, scene.truth), mota: mota(0, 0, sw.switches, sw.total) };
}
export interface FrameCosts {
  frame: number;
  /** Cost matrices of the frame (rows: tracks, columns: detection slots). */
  total: number[][]; iou: number[][]; app: number[][];
  chosen: number[]; keep: number[];
  chosenCost: number; keepCost: number;
  /** For each track, whether the detection it took was produced by the object the track held in the previous frame. */
  same: boolean[];
  switched: boolean;
}
/** Costs of one frame, the Hungarian choice, and the matching that would keep every track on the object it held one frame earlier. */
export function frameCosts(r: LabRun, f: number): FrameCosts {
  const fr = r.run.frames[f], costs = fr.costs!, dets = r.detections[f], prev = r.owner[f - 1];
  const keep = prev.map(obj => dets.findIndex(d => d.truth === obj));
  const same = fr.assign.map((j, k) => dets[j].truth === prev[k]);
  return { frame: f, total: costs.total, iou: costs.iou, app: costs.app, chosen: fr.assign, keep, chosenCost: assignmentCost(costs.total, fr.assign), keepCost: assignmentCost(costs.total, keep), same, switched: same.some(s => !s) };
}

