const OBJ_NAME = [{ en: 'orange', zh: '橘色' }, { en: 'blue', zh: '藍色' }, { en: 'green', zh: '綠色' }];
const objName = (lang: Lang, k: number) => pick(lang, OBJ_NAME[k].en, OBJ_NAME[k].zh);
const f2 = (v: number) => fmt(v, 2);

/** Plain-language reading of the inspected frame (pure, so tests can check it). */
export function describe(lang: Lang, r: LabRun, c: FrameCosts, lambda: number): string {
  const wrongTracks = c.same.map((s, k) => (s ? -1 : k)).filter(k => k >= 0);
  let head: string;
  if (c.switched) {
    const [a, b] = wrongTracks;
    head = pick(lang,
      `At frame ${c.frame} the cheapest matching costs ${f2(c.chosenCost)}, and it hands track #${a + 1} (${objName(lang, r.owner[c.frame - 1][a])}) to the ${objName(lang, r.detections[c.frame][c.chosen[a]].truth)} object${b === undefined ? '' : ` and track #${b + 1} the other way round`}. Keeping every track on its own object would cost ${f2(c.keepCost)}, so the Hungarian algorithm prefers the swap.`,
      `在第 ${c.frame} 幀，成本最低的配對總成本為 ${f2(c.chosenCost)}，它把軌跡 #${a + 1}（${objName(lang, r.owner[c.frame - 1][a])}）交給${objName(lang, r.detections[c.frame][c.chosen[a]].truth)}物體${b === undefined ? '' : `，軌跡 #${b + 1} 則反過來`}。若讓每條軌跡留在自己的物體上，總成本是 ${f2(c.keepCost)}，所以匈牙利演算法選擇了交換。`);
  } else {
    head = pick(lang,
      `At frame ${c.frame} every track takes the detection of the object it held one frame earlier (total cost ${f2(c.chosenCost)}).`,
      `在第 ${c.frame} 幀，每條軌跡都拿到前一幀所跟隨物體的偵測框（總成本 ${f2(c.chosenCost)}）。`);
  }
  const tail = r.switches === 0
    ? pick(lang, ` Over the whole clip there are no identity switches at λ = ${f2(lambda)}.`, ` 在 λ = ${f2(lambda)} 時，整段影片沒有任何身分切換。`)
    : pick(lang, ` Over the whole clip there are ${r.switches} identity switches, the first at frame ${r.firstSwitch}.`, ` 整段影片共有 ${r.switches} 次身分切換，第一次出現在第 ${r.firstSwitch} 幀。`);
  return head + tail;
}

// ---------------------------------------------------------------------------------------------- drawing (DOM)
const TRACK_COLOURS = ['#f28c12', '#2f7de1', '#2aa84a'];
const S = 3, SCENE_W = W * S, SCENE_H = H * S;
const frameCanvases = new Map<number, HTMLCanvasElement>();
function frameBitmap(f: number, img: Rgb): HTMLCanvasElement {
  let c = frameCanvases.get(f);
  if (!c) { c = document.createElement('canvas'); drawRgb(c, img); frameCanvases.set(f, c); }
  return c;
}
function rectPath(ctx: CanvasRenderingContext2D, b: Box) { ctx.beginPath(); ctx.rect((b.cx - b.w / 2) * S, (b.cy - b.h / 2) * S, b.w * S, b.h * S); }
function stroked(ctx: CanvasRenderingContext2D, colour: string, width: number, dash: number[] = []) {
  ctx.setLineDash([]); ctx.lineWidth = width + 3; ctx.strokeStyle = 'rgba(0,0,0,0.75)'; ctx.stroke();
  ctx.setLineDash(dash); ctx.lineWidth = width; ctx.strokeStyle = colour; ctx.stroke(); ctx.setLineDash([]);
}
function drawScene(canvas: HTMLCanvasElement, scene: Scene, r: LabRun, f: number) {
  if (canvas.width !== SCENE_W) canvas.width = SCENE_W;
  if (canvas.height !== SCENE_H) canvas.height = SCENE_H;
  const ctx = canvas.getContext('2d')!;
  ctx.imageSmoothingEnabled = false; ctx.drawImage(frameBitmap(f, scene.frames[f]), 0, 0, SCENE_W, SCENE_H);
  ctx.lineJoin = 'round'; ctx.lineCap = 'round';
  // Trails of the filtered track boxes up to frame f.
  for (let k = 0; k < K; k++) {
    ctx.beginPath();
    for (let t = 0; t <= f; t++) { const b = r.run.frames[t].boxes[k]; if (t === 0) ctx.moveTo(b.cx * S, b.cy * S); else ctx.lineTo(b.cx * S, b.cy * S); }
    ctx.setLineDash([]); ctx.lineWidth = 5; ctx.strokeStyle = 'rgba(0,0,0,0.55)'; ctx.stroke();
    ctx.lineWidth = 2.4; ctx.strokeStyle = TRACK_COLOURS[k]; ctx.stroke();
  }
  // True boxes (white dashed), predicted boxes (dotted, track colour) and filtered track boxes (solid, track colour).
  for (let k = 0; k < K; k++) { rectPath(ctx, scene.truth[f][k]); stroked(ctx, '#ffffff', 1.6, [6, 4]); }
  if (f > 0) for (let k = 0; k < K; k++) { rectPath(ctx, r.run.frames[f].predicted[k]); stroked(ctx, TRACK_COLOURS[k], 1.6, [2, 4]); }
  ctx.font = 'bold 15px system-ui, sans-serif'; ctx.textAlign = 'left'; ctx.textBaseline = 'alphabetic';
  for (let k = 0; k < K; k++) {
    const b = r.run.frames[f].boxes[k];
    rectPath(ctx, b); stroked(ctx, TRACK_COLOURS[k], 2.6);
    const tx = (b.cx - b.w / 2) * S + 4, ty = (b.cy - b.h / 2) * S - 5;
    ctx.lineWidth = 4; ctx.strokeStyle = 'rgba(0,0,0,0.85)'; ctx.strokeText(`#${k + 1}`, tx, ty); ctx.fillStyle = TRACK_COLOURS[k]; ctx.fillText(`#${k + 1}`, tx, ty);
  }
  ctx.fillStyle = 'rgba(0,0,0,0.6)'; ctx.fillRect(0, 0, 74, 24);
  ctx.fillStyle = '#ffffff'; ctx.font = '600 14px system-ui, sans-serif'; ctx.fillText(`f = ${f}`, 8, 17);
}

const COST_W = 440, COST_H = 396;
function drawCost(canvas: HTMLCanvasElement, lang: Lang, r: LabRun, c: FrameCosts, lambda: number) {
  const col = plotColors(canvas), ctx = startPlot(canvas, COST_W, COST_H, col), x0 = 84, y0 = 92, cw = 112, ch = 74;
  label(ctx, pick(lang, `Cost matrix C at frame ${c.frame}`, `第 ${c.frame} 幀的成本矩陣 C`), 12, 24, { bold: true, color: col.ink, size: 16 });
  label(ctx, pick(lang, `C = ${f2(lambda)} · (1 − IoU) + ${f2(1 - lambda)} · (1 − cos)`, `C = ${f2(lambda)} · (1 − IoU) + ${f2(1 - lambda)} · (1 − cos)`), 12, 46, { color: col.muted, size: 14 });
  // Column headers: the true object behind each detection.
  label(ctx, pick(lang, 'detections (colour = true object)', '偵測框（顏色 = 真實物體）'), x0, 70, { color: col.muted, size: 13 });
  for (let j = 0; j < K; j++) {
    const cx = x0 + j * cw + cw / 2, truth = r.detections[c.frame][j].truth;
    ctx.beginPath(); ctx.arc(cx, y0 - 8, 8, 0, 2 * Math.PI); ctx.fillStyle = TRACK_COLOURS[truth]; ctx.fill(); ctx.lineWidth = 1.5; ctx.strokeStyle = col.ink; ctx.stroke();
  }
  label(ctx, pick(lang, 'tracks', '軌跡'), 12, y0 - 6, { color: col.muted, size: 13 });
  for (let k = 0; k < K; k++) {
    const y = y0 + k * ch, held = r.owner[c.frame - 1][k];
    ctx.fillStyle = TRACK_COLOURS[held]; ctx.fillRect(12, y + 8, 62, ch - 16);
    label(ctx, `#${k + 1}`, 43, y + ch / 2 + 6, { bold: true, color: '#101010', align: 'center', size: 17, halo: 'rgba(255,255,255,0.55)' });
    for (let j = 0; j < K; j++) {
      const x = x0 + j * cw, chosen = c.chosen[k] === j;
      if (chosen) { ctx.fillStyle = TRACK_COLOURS[held]; ctx.globalAlpha = 0.28; ctx.fillRect(x + 2, y + 2, cw - 4, ch - 4); ctx.globalAlpha = 1; }
      ctx.lineWidth = chosen ? 3.2 : 1; ctx.strokeStyle = chosen ? col.ink : col.grid; ctx.strokeRect(x + 1.5, y + 1.5, cw - 3, ch - 3);
      label(ctx, f2(c.total[k][j]), x + 10, y + 28, { bold: true, color: col.ink, size: 20 });
      label(ctx, `1−IoU ${f2(c.iou[k][j])}`, x + 10, y + 50, { color: col.muted, size: 13 });
      label(ctx, `1−cos ${f2(c.app[k][j])}`, x + 10, y + 67, { color: col.muted, size: 13 });
      if (chosen) {
        const ok = r.detections[c.frame][j].truth === r.owner[c.frame - 1][k], mx = x + cw - 20, my = y + 19;
        ctx.lineWidth = 3.4; ctx.lineCap = 'round'; ctx.strokeStyle = ok ? '#1a8f3c' : '#d62728'; ctx.beginPath();
        if (ok) { ctx.moveTo(mx - 7, my); ctx.lineTo(mx - 2, my + 6); ctx.lineTo(mx + 8, my - 7); } else { ctx.moveTo(mx - 7, my - 7); ctx.lineTo(mx + 7, my + 7); ctx.moveTo(mx + 7, my - 7); ctx.lineTo(mx - 7, my + 7); }
        ctx.stroke();
      }
    }
  }
  const yb = y0 + K * ch + 24;
  label(ctx, pick(lang, `Outlined: the Hungarian choice, total ${f2(c.chosenCost)}`, `框起來：匈牙利演算法的選擇，總成本 ${f2(c.chosenCost)}`), 12, yb, { color: col.ink, size: 14 });
  label(ctx, pick(lang, `Keeping each track on its object: total ${f2(c.keepCost)}`, `讓每條軌跡留在自己的物體：總成本 ${f2(c.keepCost)}`), 12, yb + 20, { color: col.ink, size: 14 });
  label(ctx, pick(lang, 'green tick: same object as before, red cross: switched', '綠色勾：與前一幀同一物體；紅色叉：換了物體'), 12, yb + 40, { color: col.muted, size: 13 });
}

const RIB_W = 600, RIB_H = 210;
const RIB_X0 = 62, RIB_X1 = 586, RIB_ROW = 36, RIB_Y0 = 56;
const ribbonFrame = (x: number) => Math.max(0, Math.min(T - 1, Math.floor(((x - RIB_X0) / (RIB_X1 - RIB_X0)) * T)));
function drawRibbon(canvas: HTMLCanvasElement, lang: Lang, r: LabRun, f: number) {
  const col = plotColors(canvas), ctx = startPlot(canvas, RIB_W, RIB_H, col), cell = (RIB_X1 - RIB_X0) / T;
  label(ctx, pick(lang, 'Which object does each track follow?', '每條軌跡跟著哪個物體？'), 12, 22, { bold: true, color: col.ink, size: 18 });
  for (let k = 0; k < K; k++) {
    const y = RIB_Y0 + k * RIB_ROW;
    label(ctx, `#${k + 1}`, 12, y + 22, { bold: true, color: col.ink, size: 17 });
    for (let t = 0; t < T; t++) { ctx.fillStyle = TRACK_COLOURS[r.owner[t][k]]; ctx.fillRect(RIB_X0 + t * cell, y + 2, cell + 0.6, RIB_ROW - 6); }
  }
  const yAxis = RIB_Y0 + K * RIB_ROW + 2;
  for (let t = 0; t < T; t += 5) { line(ctx, RIB_X0 + (t + 0.5) * cell, yAxis, RIB_X0 + (t + 0.5) * cell, yAxis + 5, col.muted); label(ctx, String(t), RIB_X0 + (t + 0.5) * cell, yAxis + 20, { align: 'center', color: col.muted, size: 15 }); }
  label(ctx, pick(lang, 'frame', '幀'), RIB_X1, yAxis + 40, { align: 'right', color: col.muted, size: 15 });
  const xm = RIB_X0 + (MEET + 0.5) * cell;
  line(ctx, xm, RIB_Y0 - 6, xm, yAxis, col.ink, 1.5, [4, 3]);
  label(ctx, pick(lang, 'objects meet and turn back', '兩個物體相遇並折返'), Math.min(xm + 6, RIB_X1), RIB_Y0 - 10, { color: col.ink, size: 15, align: xm > RIB_X1 - 190 ? 'right' : 'left' });
  const xf = RIB_X0 + (f + 0.5) * cell;
  ctx.fillStyle = col.ink; ctx.beginPath(); ctx.moveTo(xf, yAxis + 1); ctx.lineTo(xf - 6, yAxis + 10); ctx.lineTo(xf + 6, yAxis + 10); ctx.closePath(); ctx.fill();
  ctx.lineWidth = 2.5; ctx.strokeStyle = col.ink; ctx.strokeRect(xf - cell / 2, RIB_Y0 - 1, cell, K * RIB_ROW);
  label(ctx, pick(lang, 'colour = the true object the track holds', '顏色 = 該軌跡實際跟著的真實物體'), 12, RIB_H - 6, { color: col.muted, size: 15 });
}

